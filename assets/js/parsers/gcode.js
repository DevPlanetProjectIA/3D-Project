/*
 * Leitor dos metadados de G-code.
 *
 * O G-code é a saída real do fatiador, e o bloco de comentários no começo e no
 * fim do arquivo traz o consumo **medido**: gramas por filamento, comprimento,
 * tempo estimado de impressão, purga de troca de cor, cores carregadas, bico,
 * altura de camada e preenchimento. É a fonte mais precisa que existe sem
 * fatiar — melhor até que um 3MF fatiado, porque inclui a purga real.
 *
 * Três dialetos cobertos:
 *  - Bambu Studio / Orca Slicer — `; filament used [g] = 36.68,20.00`
 *  - PrusaSlicer / SuperSlicer — mesmo formato, um valor por extrusora
 *  - Cura — `;Filament used: 1.2345m` e `;TIME:4523`, sem gramas
 *
 * O arquivo não é lido inteiro: um G-code de peça grande passa de 100 MB, e
 * tudo o que interessa está nos primeiros e nos últimos quilobytes.
 */

import { openZip } from './zip.js';
import { normalizeHex, readSliceInfo } from './sliceinfo.js';

/** Quanto ler de cada ponta do arquivo. O bloco de metadados cabe folgado. */
const EDGE_BYTES = 512 * 1024;

/** Área da seção de um filamento de 1,75 mm, em mm². Usada quando só há comprimento. */
const FILAMENT_AREA_175 = Math.PI * (1.75 / 2) ** 2;

const toNumber = (raw) => {
  const n = parseFloat(String(raw ?? '').replace(',', '.'));
  return Number.isFinite(n) ? n : 0;
};

/** Divide `12,5;30,2` ou `12.5,30.2` numa lista de números por extrusora. */
function numberList(raw) {
  return String(raw || '')
    .split(/[;,]/)
    .map((piece) => parseFloat(piece.trim()))
    .filter((n) => Number.isFinite(n));
}

function textList(raw) {
  return String(raw || '')
    .split(/[;,]/)
    .map((piece) => piece.trim().replace(/^"|"$/g, ''))
    .filter(Boolean);
}

/**
 * Coleta os comentários `; chave = valor` e `; chave: valor`.
 *
 * O separador `=` é inequívoco. O `:` não: a linha de assinatura do fatiador
 * (`; generated by BambuStudio 1.9 on 2026-10-06 at 20:11:03`) tem dois-pontos
 * no horário, e tratá-los como separador produzia a chave
 * "generated by ... at 20" — motivo pelo qual o nome do fatiador não era lido.
 * Daí a regra: com `:`, a parte antes do separador não pode conter dígito.
 * Chaves reais (`total layer number`, `TIME`, `model printing time`) não contêm;
 * datas e versões contêm.
 *
 * A última ocorrência vence: fatiadores repetem a configuração no rodapé, e é
 * lá que ficam os totais de consumo.
 */
function readComments(text) {
  const map = new Map();
  for (const line of text.split(/\r?\n/)) {
    if (line[0] !== ';') continue;
    const body = line.slice(1);

    const eq = body.indexOf('=');
    if (eq > 0) {
      map.set(body.slice(0, eq).trim().toLowerCase(), body.slice(eq + 1).trim());
      continue;
    }

    const colon = body.indexOf(':');
    if (colon > 0) {
      const key = body.slice(0, colon).trim();
      if (!/\d/.test(key)) map.set(key.toLowerCase(), body.slice(colon + 1).trim());
    }
  }
  return map;
}

/**
 * Identifica o fatiador varrendo o texto bruto.
 *
 * A assinatura vive numa linha de prosa, não num par chave/valor, então
 * procurar pelo nome é mais confiável do que tentar parseá-la.
 */
function detectSlicer(text) {
  const head = text.slice(0, 4096);
  const nomes = [
    [/orca\s*slicer/i, 'Orca Slicer'],
    [/bambu\s*studio/i, 'Bambu Studio'],
    [/prusaslicer/i, 'PrusaSlicer'],
    [/superslicer/i, 'SuperSlicer'],
    [/cura/i, 'Cura'],
    [/simplify3d/i, 'Simplify3D'],
    [/ideamaker/i, 'ideaMaker'],
    [/flashprint|flash\s*studio/i, 'FlashPrint'],
    [/kiri\s*moto/i, 'Kiri:Moto'],
  ];
  for (const [padrao, nome] of nomes) if (padrao.test(head)) return nome;
  return 'fatiador';
}

/** `2h 22m 1s`, `1h 23m 45s` ou `45m 10s` em segundos. */
function parseDuration(raw) {
  const text = String(raw || '');
  const direct = text.match(/^\s*(\d+(?:\.\d+)?)\s*$/);
  if (direct) return Math.round(parseFloat(direct[1]));

  let seconds = 0;
  let matched = false;
  for (const [pattern, factor] of [[/(\d+)\s*d/i, 86400], [/(\d+)\s*h/i, 3600], [/(\d+)\s*m(?!s)/i, 60], [/(\d+)\s*s/i, 1]]) {
    const m = text.match(pattern);
    if (m) { seconds += Number(m[1]) * factor; matched = true; }
  }
  return matched ? seconds : 0;
}

/* ---------- Interpretação ---------- */

/** Interpreta o bloco de comentários. Devolve o mesmo formato de `readSliceInfo`. */
export function parseGcodeText(text) {
  const c = readComments(text);
  const slicerLabel = detectSlicer(text);
  const get = (...keys) => {
    for (const key of keys) {
      const value = c.get(key);
      if (value !== undefined && value !== '') return value;
    }
    return '';
  };

  // Dois vocabulários no mundo real. PrusaSlicer escreve
  // `; filament used [g] = 23.45`; o Bambu Studio escreve
  // `; total filament weight [g] : 5.15,6.81` — lista por extrusora, com
  // dois-pontos e `cm^3` em vez de `cm3`. Ler só o primeiro formato fazia o
  // total virar o consumo de uma extrusora só.
  const gramsList = numberList(get(
    'filament used [g]', 'filament used [grams]', 'total filament weight [g]', 'total filament weight',
  ));
  const lengthMm = numberList(get(
    'filament used [mm]', 'total filament length [mm]', 'total filament length',
  ));
  const volumeCm3 = numberList(get(
    'filament used [cm3]', 'filament used [cm^3]', 'total filament volume [cm3]',
    'total filament volume [cm^3]', 'total filament volume',
  ));
  const materials = textList(get('filament_type', 'filament type'));
  const colors = textList(get('filament_colour', 'filament_color')).map(normalizeHex);

  // Cura não escreve gramas, só `;Filament used: 1.2345m` — em metros, por bico.
  const curaMeters = gramsList.length ? [] : String(get('filament used'))
    .split(',')
    .map((piece) => {
      const m = piece.trim().match(/^([\d.]+)\s*m$/i);
      return m ? parseFloat(m[1]) : NaN;
    })
    .filter(Number.isFinite);

  const slotCount = Math.max(gramsList.length, lengthMm.length, volumeCm3.length, curaMeters.length, 1);

  const density = toNumber(get('filament_density')) || 1.24;

  const filaments = [];
  for (let i = 0; i < slotCount; i++) {
    const meters = lengthMm[i] !== undefined ? lengthMm[i] / 1000
      : curaMeters[i] !== undefined ? curaMeters[i]
      : 0;
    const fromVolume = volumeCm3[i] !== undefined ? volumeCm3[i] * density : 0;
    const fromLength = meters > 0 ? ((meters * 1000 * FILAMENT_AREA_175) / 1000) * density : 0;
    const grams = gramsList[i] !== undefined ? gramsList[i] : (fromVolume || fromLength);
    if (!grams && !meters) continue;
    filaments.push({
      id: String(i + 1),
      slot: i,
      material: materials[i] || materials[0] || '',
      color: colors[i] || '',
      grams,
      meters,
    });
  }

  // `total filament weight [g]` é por extrusora, não o total: somar é o total.
  const somaFilamentos = filaments.reduce((sum, f) => sum + f.grams, 0);
  const declaredTotal = toNumber(get('total filament used [g]'));
  const grams = somaFilamentos || declaredTotal;

  // O Bambu põe os dois tempos na mesma linha:
  // `; model printing time: 51m 30s; total estimated time: 57m 34s`.
  // O que interessa para custo é o total, então ele é extraído de dentro do valor.
  const tempoBruto = get(
    'estimated printing time (normal mode)', 'estimated printing time',
    'model printing time', 'total estimated time', 'time', 'print_time',
  );
  const totalNaLinha = /total estimated time\s*[:=]\s*([^;]+)/i.exec(tempoBruto);
  const seconds = parseDuration(totalNaLinha ? totalNaLinha[1] : tempoBruto);

  // Purga declarada pelo fatiador: é o desperdício real da troca de cor.
  const flushPerChange = numberList(get('filament_flush_volume', 'flush_volume'));
  const flushTotalMm3 = flushPerChange.reduce((a, b) => a + b, 0);
  const purgeGrams = flushTotalMm3 > 0 ? (flushTotalMm3 / 1000) * density : 0;

  const sliced = grams > 0 || seconds > 0;

  return {
    sliced,
    source: 'gcode',
    slicer: slicerLabel,
    version: '',
    printerModel: get('printer_model', 'printer_settings_id', 'machine_name'),
    nozzle: get('nozzle_diameter', 'machine_nozzle_size'),
    layerHeight: get('layer_height'),
    infill: get('sparse_infill_density', 'fill_density', 'infill_sparse_density'),
    seconds,
    grams,
    filaments,
    purge: {
      grams: purgeGrams,
      estimated: false,
      changes: flushPerChange.filter((v) => v > 0).length,
    },
    extruderByObject: null,
    plateCount: 1,
    layerCount: Number(get('total layer number', 'layer_count')) || 0,
  };
}

/* ---------- Entrada ---------- */

/** Formatos aceitos como "arquivo fatiado". */
export function isSlicedFilename(name) {
  return /\.(gcode|gco|g|bgcode)(\.3mf)?$/i.test(String(name || ''))
    || /\.gcode\.3mf$/i.test(String(name || ''));
}

/**
 * Lê os metadados de um arquivo fatiado.
 *
 * Aceita um `File`/`Blob` — e nesse caso lê apenas as duas pontas, porque o
 * miolo são milhões de linhas de movimento que não interessam — ou um
 * `ArrayBuffer` já em memória.
 */
export async function parseSlicedFile(input) {
  const isBlob = typeof Blob !== 'undefined' && input instanceof Blob;
  const name = isBlob ? (input.name || '') : '';

  // `.gcode.3mf` do Bambu é um container: o G-code está em Metadata/plate_N.gcode.
  if (/\.3mf$/i.test(name) || (!isBlob && looksLikeZip(input))) {
    const buffer = isBlob ? await input.arrayBuffer() : input;
    if (looksLikeZip(buffer)) return parseGcodeFrom3mf(buffer);
  }

  if (!isBlob) {
    const text = new TextDecoder('utf-8', { fatal: false }).decode(input);
    return parseGcodeText(text);
  }

  const size = input.size;
  const head = await input.slice(0, Math.min(EDGE_BYTES, size)).text();
  const tail = size > EDGE_BYTES
    ? await input.slice(Math.max(0, size - EDGE_BYTES)).text()
    : '';

  // Cabeçalho primeiro e rodapé depois: a última ocorrência vence, e os totais
  // de consumo ficam no rodapé.
  return parseGcodeText(`${head}\n${tail}`);
}

const looksLikeZip = (buffer) => {
  if (!buffer || buffer.byteLength < 4) return false;
  const head = new Uint8Array(buffer, 0, 4);
  return head[0] === 0x50 && head[1] === 0x4b;
};

async function parseGcodeFrom3mf(buffer) {
  const zip = openZip(buffer);

  // `slice_info.config` é a mesma informação em XML estruturado, com gramas e
  // metros por filamento já separados. Preferir isso a reparsear 3 MB de
  // comentários de G-code é mais rápido e menos sujeito a dialeto.
  try {
    const info = await readSliceInfo(zip);
    if (info?.sliced && info.grams > 0) return { ...info, source: 'gcode' };
  } catch {
    // Sem slice_info legível: segue para o G-code.
  }

  const entry = zip.find((e) => /\.(gcode|gco)$/i.test(e.name))
    || zip.find((e) => /plate_\d+\.gcode/i.test(e.name));
  if (!entry) {
    throw new Error('Este 3MF não traz dados de fatiamento nem G-code. '
      + 'Exporte o G-code pelo fatiador, ou salve o projeto depois de fatiar.');
  }
  const text = await zip.readEntryText(entry);
  return parseGcodeText(text);
}

export default parseSlicedFile;
