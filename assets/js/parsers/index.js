/* Despacho de formato e métricas derivadas da geometria. */

import { parseSTL } from './stl.js';
import { parse3MF } from './threemf.js';

export { parseSTL, parse3MF };

/** Deduz o formato pela extensão do nome do arquivo. */
export function formatOf(filename) {
  const ext = String(filename || '').toLowerCase().match(/\.([a-z0-9]+)$/)?.[1];
  if (ext === '3mf') return '3mf';
  if (ext === 'stl') return 'stl';
  return '';
}

/**
 * Deduz o formato pelo conteúdo. Um 3MF é um ZIP, portanto começa com "PK\x03\x04";
 * nenhum STL começa assim. Útil porque arquivos renomeados são comuns.
 */
export function sniffFormat(arrayBuffer) {
  if (!arrayBuffer || arrayBuffer.byteLength < 4) return '';
  const head = new Uint8Array(arrayBuffer, 0, 4);
  const isZip = head[0] === 0x50 && head[1] === 0x4b
    && (head[2] === 0x03 || head[2] === 0x05 || head[2] === 0x07);
  if (isZip) return '3mf';
  if (looksLikeGcode(arrayBuffer)) return 'gcode';
  return 'stl';
}

/**
 * Reconhece G-code de texto.
 *
 * Interessa porque o arquivo chega no campo errado com frequência: o G-code é a
 * saída do fatiador, não um modelo, e tentar lê-lo como STL produzia um erro
 * sobre triângulos que não ajuda ninguém.
 */
export function looksLikeGcode(arrayBuffer) {
  const probe = new TextDecoder('utf-8', { fatal: false })
    .decode(new Uint8Array(arrayBuffer, 0, Math.min(2048, arrayBuffer.byteLength)));
  if (/^\s*;\s*(generated by|FLAVOR|HEADER_BLOCK_START|TIME)/im.test(probe)) return true;
  // Comandos de movimento no começo do arquivo são decisivos.
  return /^\s*(G0|G1|G21|G28|G90|G92|M73|M104|M109)\b/im.test(probe);
}

/** Erro de arquivo no campo errado: a interface usa isso para se corrigir. */
export class SlicedFileError extends Error {
  constructor(message) {
    super(message);
    this.name = 'SlicedFileError';
    /** Sinaliza à interface que o arquivo serve como dados de fatiamento. */
    this.isSlicedFile = true;
  }
}

/**
 * Interpreta um arquivo de modelo.
 * Devolve `{ positions, normals, triangles, bounds, format }`.
 *
 * O conteúdo tem precedência sobre a extensão: um `.stl` que é de fato um
 * container 3MF (ou o contrário) é interpretado pelo que realmente é.
 */
export async function parseModel(arrayBuffer, format, onProgress) {
  const sniffed = sniffFormat(arrayBuffer);
  const kind = sniffed || format || '';

  if (kind === '3mf') {
    const geometry = await parse3MF(arrayBuffer, onProgress);
    return { ...geometry, format: '3mf' };
  }
  if (kind === 'stl') {
    const geometry = parseSTL(arrayBuffer, onProgress);
    onProgress?.(1);
    return { ...geometry, format: 'stl', colors: null, palette: [], slice: null };
  }
  if (kind === 'gcode') {
    throw new SlicedFileError(
      'Este é um G-code, não um modelo: ele descreve os movimentos da impressora e não '
      + 'contém geometria. Ele serve no campo "Dados do fatiamento", para medir peso e tempo.',
    );
  }
  throw new Error('Formato não suportado. Use .stl ou .3mf.');
}

/**
 * Volume fechado da malha, em mm³.
 *
 * Soma o volume assinado dos tetraedros formados por cada triângulo e a
 * origem. Vale para malhas fechadas e orientadas; em malhas abertas o número
 * perde sentido, por isso o valor absoluto e a checagem de sanidade contra a
 * caixa envolvente em `estimateWeight`.
 */
export function volumeOf(geometry) {
  const p = geometry.positions;
  let total = 0;
  for (let i = 0; i < p.length; i += 9) {
    const ax = p[i], ay = p[i + 1], az = p[i + 2];
    const bx = p[i + 3], by = p[i + 4], bz = p[i + 5];
    const cx = p[i + 6], cy = p[i + 7], cz = p[i + 8];
    total += ax * (by * cz - bz * cy)
      - ay * (bx * cz - bz * cx)
      + az * (bx * cy - by * cx);
  }
  return Math.abs(total) / 6;
}

/** Área total da superfície da malha, em mm². */
export function surfaceAreaOf(geometry) {
  const p = geometry.positions;
  let total = 0;
  for (let i = 0; i < p.length; i += 9) {
    const ux = p[i + 3] - p[i], uy = p[i + 4] - p[i + 1], uz = p[i + 5] - p[i + 2];
    const vx = p[i + 6] - p[i], vy = p[i + 7] - p[i + 1], vz = p[i + 8] - p[i + 2];
    total += Math.hypot(
      uy * vz - uz * vy,
      uz * vx - ux * vz,
      ux * vy - uy * vx,
    );
  }
  return total / 2;
}

/**
 * Estima o peso impresso a partir da geometria.
 *
 * Modelo de casca e núcleo: a casca consome `área × espessura de parede` — e a
 * área da malha já conta as duas faces, o que é exatamente o volume da casca de
 * um sólido fechado. O que sobra por dentro é preenchido na densidade escolhida:
 *
 *     material = casca + (volume − casca) × preenchimento
 *
 * A casca é limitada ao volume total, e é isso que faz o modelo acertar as peças
 * finas. Uma bola de natal de 2,3 mm de espessura é quase toda parede, topo e
 * base: a casca estoura o volume, o resultado vira maciço, e é o que a impressora
 * realmente faz. O fator único anterior (preenchimento + 0,25) subestimava essas
 * peças pela metade.
 *
 * Continua sendo estimativa: não substitui fatiar.
 */
export function estimateWeight({
  volumeMm3,
  areaMm2 = 0,
  boxVolumeMm3 = 0,
  density = 1.24,
  infillPercent = 20,
  wallThickness = 0.8,
}) {
  // Volume maior que a caixa envolvente denuncia malha aberta ou invertida.
  const sane = boxVolumeMm3 > 0 && volumeMm3 > boxVolumeMm3 * 1.02 ? 0 : volumeMm3;
  const infill = Math.min(100, Math.max(0, infillPercent)) / 100;

  const shell = areaMm2 > 0 ? Math.min(sane, areaMm2 * Math.max(0.1, wallThickness)) : 0;
  const core = Math.max(0, sane - shell);
  const materialMm3 = areaMm2 > 0
    ? shell + core * infill
    // Sem área (não deveria acontecer): cai no fator antigo.
    : sane * Math.min(1, infill + 0.25);

  return {
    volumeCm3: sane / 1000,
    areaCm2: areaMm2 / 100,
    shellCm3: shell / 1000,
    /** Fração do volume que vira material — útil para explicar o número. */
    solidRatio: sane > 0 ? materialMm3 / sane : 0,
    grams: (materialMm3 / 1000) * density,
    reliable: sane > 0,
  };
}

/** Dimensões (mm), centro e volume da caixa envolvente. */
export function measure(geometry) {
  const { min, max } = geometry.bounds;
  const finite = min.every(Number.isFinite) && max.every(Number.isFinite);
  const size = finite ? [max[0] - min[0], max[1] - min[1], max[2] - min[2]] : [0, 0, 0];
  return {
    size: { x: size[0], y: size[1], z: size[2] },
    center: finite ? [(min[0] + max[0]) / 2, (min[1] + max[1]) / 2, (min[2] + max[2]) / 2] : [0, 0, 0],
    radius: Math.hypot(size[0], size[1], size[2]) / 2 || 1,
    boxVolume: size[0] * size[1] * size[2],
  };
}
